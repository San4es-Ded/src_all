package haron.render;

class ScissorRect {
    private final float a;
    private final float b;
    private final float c;
    private final float d;
    private final float e;

    public ScissorRect(float f, float f2, float f3, float f4, float f5) {
        this.a = f;
        this.b = f2;
        this.c = f3;
        this.d = f4;
        this.e = f5;
    }

    public float e() {
        return this.e;
    }

    public float b() {
        return this.b;
    }

    public float c() {
        return this.c;
    }

    public float d() {
        return this.d;
    }

    public float a() {
        return this.a;
    }
}

