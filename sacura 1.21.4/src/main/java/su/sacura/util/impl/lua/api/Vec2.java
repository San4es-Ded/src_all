 package su.sacura.util.impl.lua.api;
 
 class Vec2 {
   private float x;
   
   private float y;
   
   public Vec2(float x, float y) {
     this.x = x;
     this.y = y;
   }
   
   public float getX() {
     return this.x;
   }
   
   public float getY() {
     return this.y;
   }
   
   public void setX(float x) {
     this.x = x;
   }
   
   public void setY(float y) {
     this.y = y;
   }
 }


